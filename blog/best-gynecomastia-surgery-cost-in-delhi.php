<h2  class="blog_heading">Causes of Gynecomastia</h2>
<ol>
<li>Hormonal:
  <ul>
    <li>- Androgen resistance causes an imbalance of the male and female hormones</li>
    <li>- Hyperprolactinemia induces the development of breast tissue</li>
    <li>- Hyperthyroidism causes a reduction in the level of free testosteron</li>
    <li>- Hypogonadism due to an endocrine abnormality</li>
    <li>- Congenital conditions such as Klinefelter syndrome</li>
</ul></li>
<li>Systemic:
  <ul>
    <li>- Obesity causes the deposition of fat in the breast and alters the appearance</li>
    <li>- Liver disease causes the increased production of certain hormone precursors to estrogen</li>
    <li>- Chronic kidney disease affects testosterone levels contributing to breast proliferation.</li>
</ul></li>
<li>Cancer-  Neoplasms of the liver, kidney, adrenal gland, breast and testicles.</li>
</ol>

