                        <h3>Why is a tummy tuck done?</h3>
                        <p>With increasing age, the elasticity of the skin is lost. This makes the skin loose and wrinkly. Other conditions like pregnancy or losing a significant amount of weight also lead to the stretching of the skin over the abdomen that does not return to its normal shape. This loose and hanging skin over the abdomen can be a cause of distress for many people.</p>
                        <p>The <a href="https://www.iconiquebydrbkgarg.com/tummy-tuck">tummy tuck procedure</a> is done for people who want to get rid of this loose skin. During the procedure, the abdominal muscle is also stretched to provide more definition to the tummy.</p>

