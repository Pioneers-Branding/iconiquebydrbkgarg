                        <h5>1. Driving back from hospital post-surgery:</h5>
                        <p>The procedure is often carried out under sedation, and hence it is not advisable to drive immediately post-surgery. It is better to ask someone to drive you or take a cab to reach home post-surgery.</p>

                        <h5>2. Hair wash or shower:</h5>
                        <p>Do not wash your hair for at least 48 hours after the procedure. This is because the newly transplanted follicles are still in a delicate phase, and the force of water can damage the follicles. After the 2nd or 3rd day from the procedure, you can wash your hair gently using a cup to rinse the head instead of a direct shower.</p>

                        <h5>3. Using harsh chemicals:</h5>
                        <p>Avoid using any harsh shampoo to rinse your hair. Your doctor will provide a softer shampoo and lotions to use post-surgery.</p>

                        <h5>4. Dying your hair:</h5>
                        <p>It is not advisable to dye your hair post-surgery for at least a month. Most patients dye their hair just before the surgery to avoid any issues.</p>

                        <h5>5. Scrubbing your scalp:</h5>
                        <p>Hair follicles are delicate and sensitive during the initial days. Thus, even though you may feel irritation or itching around the treated area, avoid scraping or rubbing the scalp. Ask your doctor for a suitable lotion to apply on the scalp for minimizing the irritation.</p>

                        <h5>6. Smoking:</h5>
                        <p>Smoking has many adverse effects on the outcomes of the procedure. It may affect blood circulation, and thus, your hair doctor will advise you to avoid smoking for a few days.</p>

                        <h5>7. Alcohol consumption:</h5>
                        <p>Alcohol is known as a blood thinner and may cause harmful effects like bleeding at treated sites.</p>
                        
                        <h5>8. Eating spicy or processed food:</h5>
                        <p>A healthy diet will improve the results of the hair transplantation. On the other hand, spicy or unhealthy food can affect speed of recovery. Processed food items or bakery products may even cause hair follicles to fall out, thus creating bald spots. Malnutrition can cause severe hair loss. Hence, it is important to provide your body rich nutritious food that includes proteins, amino acids, omega acids, vitamins while recovering.</p>
                        
                        <h5>9. Stressful situations:</h5>
                        <p>Just like smoking or unhealthy food, stress may also cause newly grafted hairs to fall out. Keeping a positive mindset, getting enough sleep, and a relaxing environment will improve the results of the procedure.</p>
                        
                        <h5>10. Forgetting to take proper medications:</h5>
                        <p>Post-surgery, your doctor will prescribe specific medications to avoid swelling, infections, and painkillers. Follow the medication routine, especially the antibiotics course properly to avoid any complications.</p>
                        
                        <h5>11. Sleeping in a flat position:</h5>
                        <p>Do not sleep on your tummy or flat Post-procedure, it is essential to sleep with your head elevated for 7 to 10 days. If you still notice any swelling, try sleeping on a recliner chair for a few days. You can start sleeping in a normal position in less than one week after the surgery, when swelling has subsided.</p>
                        
                        <h5>12. Exercising or heavy lifting</h5>
                        <p>Normal blood flow is important for the speedy recovery process. Increased blood pressure or heart rate due to exercising can compromise the success of the transplanted hair. Thus, avoid any activities that cause heavy sweating. You can do light exercises after two weeks from the procedure, when the swelling is subsided, and the healing process is complete.</p>
                        
                        <h5>13. Drinking caffeine:</h5>
                        <p>Too much consumption of caffeine is considered harmful during the recovery phase. It may hinder the healing process and may cause bleeding.</p>
                        
                        <h5>14. Wearing a tight hat or caps:</h5>
                        <p> Avoid wearing any caps for the first few days as the treated area is very sensitive and scabs are formed during this time.</p>
                        
                        <h5>15. Exposure to sun: </h5>
                        <p>Avoid any direct exposure to the sun during the initial period. Sunburn can cause severe damage to the hair transplant outcome. Even if you decide to take a vacation post-surgery, cover your head with a scarf.</p>
                        
                        <h5>16. Swimming: </h5>
                        <p>You don’t want to risk damaging hair follicles due to chemicals in the water or the force of water current. Also, avoid going for scuba diving or any other water sport activity.</p>
                        
                        <h5>17. Saunas or hot water bath:</h5>
                        <p>Sweating can damage the transplanted new hairs. Thus avoid saunas or steam baths for at least 15-20 days post-procedure of hair transplant.</p>
                        
                        <h5>18. Direct Application of Ice:</h5>
                        <p>Applying ice or ice bags directly on the treated area must be avoided. This may damage the follicles. Also, avoid directly touching the scalp for a few days.</p>
                        
                        <h5>19. Wearing a safety helmet:</h5>
                        <p>Avoid wearing any headgear until the healing process is complete. This includes safety helmets, bike helmets, etc.</p>
                        
                        <h5>20. Styling your hair:</h5>
                        <p>Do not cause any damage to your newly transplanted hair by using hairspray or excessive combing or applying chemical hair products on your hair for at least 2 to 3 months after the procedure.</p>
