<h2><strong>side effects of liposuction</strong></h2>
<ol>
<li aria-level="1"><strong>Irregularities in skin contour -  </strong> During recovery after the procedure, a bumpy, wavy, or sunken and withered appearance of the skin is possible. This may result from using an improper technique and poor skin elasticity prior to the surgery. Such changes can be long-term. A spotted appearance of the skin over the area where the cannula was inserted. </li>
<li aria-level="1"><strong>Fluid accumulation -</strong>It is one of the risks of liposuction. Immediately following the surgery, fluid accumulation under is possible. This lodges in pockets under the skin known as seromas.</li>
<li aria-level="1"><strong>Infections- </strong>Bacterial infections caused by Staphylococcus, Streptococcus are possible. You will be prescribed antibiotics before discharge to prevent any chance of infection.</li>
<li aria-level="1"><strong>Hematoma-  </strong>Bleeding under the skin, known as hematoma, is possible. Smaller hematomas can be treated by using alternating compresses at home. You must wear the compression garment prescribed following surgery to avoid the occurrence of such complications. A little bruising is common and goes away with time. </li>
<li aria-level="1"><strong>Nerve sensation disturbances - </strong>Numbness that can be temporary or permanent is possible after the surgery. A certain degree of nerve irritation is also possible.</li>
<li aria-level="1"><strong>Fat embolism - </strong>Small pieces of fat may break away and enter the bloodstream and move, causing disruption in the blood flow. </li>
<li aria-level="1"><strong>Reactions to anesthesia- </strong>Very rarely, some people may be allergic to the anesthetic which can cause serious implications. </li>
<li aria-level="1"><strong>Pulmonary thromboembolism - </strong>Blood clots in the lungs and blocking the circulation is known as pulmonary thromboembolism and can be serious. Your surgeon will take a detailed medical history and run certain tests that will indicate if you might be at any of the risks of liposuction.  If found so, your surgeon will not proceed with the surgery. </li>
<li aria-level="1"><strong>Puncture wounds- </strong>Undue deep penetration of the cannula can result in an organ puncture or any other internal structure. Such situations warrant emergency care and immediate medical repair.</li>
<li aria-level="1"><strong>Renal and cardiac complications - </strong>During the procedure, there is a very dynamic change in the fluid levels in the body. This is due to a large amount of fluid exiting the system. The fluid level is recuperated through the intravenous route. Sometimes, the change in fluid dynamics may impact kidney and heart functioning, especially in previously compromised patients. This may cause fluid accumulation in the lungs, known as pulmonary edema. When it influences the total fluid volume in the body, it causes a cardiac overload.</li>
<li aria-level="1"><strong>Fat storage - </strong>Liposuction removes the fat cells from the body permanently. When you do not maintain a healthy enough lifestyle to prevent an excessive body weight, fat gets deposited in other parts of the body. Such fat deposits may lodge around the liver or the heart, causing serious implications. </li>
</ol>

