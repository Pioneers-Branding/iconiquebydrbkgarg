                        <h2>Earlobe Repair Procedure</h2>
                        <p>Many different kinds of earlobe repair surgeries are performed for different people. Its costs depend on the factors like the extent of the ear lobe injury, the patient’s age, expectations, etc. </p>
                        
                        <h5>Different types of earlobe repair surgery include the following:</h5>
                        
                        <ul class="disc_list">
                            <li>Side-to-side closure</li>
                            <li>Purse-string closure</li>
                            <li>Anterior-posterior flap modification</li>
                            
                        </ul>

                        
                        
                        <h4> Side-to-side closure</h4>
						
                        <p>Side-to-side closure is usually performed in patients who have an injury because of earrings or in children who have accidentally torn their ear lobes. This is a simple procedure that can be performed in an outpatient setting. </p>
						
						 <p>During this procedure, the ear lobe is anesthetized using local anesthesia. Next, scar tissue surrounding the wound is cut off to expose the fresh tissue. This is done to facilitate the process of fusion of both parts.</p>

 <p>Sutures are placed on both sides, and these are then pulled together to bring the parts closer. The skin fuses in some time and repairs the ear lobe injury. </p>
                        

                        <h4>Purse-string closure</h4>
						
                        <p>Purse-string suture is not usually preferred because of possible scarring and puckering of the skin. But these are highly beneficial for people who have a round wound instead of a slit-like wound, usually seen with stretching of earlobe holes. </p>
                        <p>During this procedure, the skin of the earlobe is adequately anesthetized using local anesthesia. Next, the scar tissue is cut off to expose the fresh tissue to facilitate recovery. Then, loose sutures are placed all around the round wound. These sutures are then pulled together like a purse-string which closes the round wound in the earlobe. </p>
                        <p>This type of closure is not usually done due to the increased rates of scarring. </p>
                        
                       


                        <h4>Anterior-posterior flap modification</h4>
						
                        <p>This is a more complicated procedure done for earlobe wounds. During this procedure, the fusion of the skin does not take place. Hence scar tissue does not need to be removed. Instead, after anesthetizing the earlobe, two opposing flaps are created on both sides of the wound. These are then stretched and stitched over the wound. </p>   
						
                        <p>The injury then heals, and no scarring is visible.</p>
						
						
                        
                        
