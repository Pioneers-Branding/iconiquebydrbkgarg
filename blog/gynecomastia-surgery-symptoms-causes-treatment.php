                        <h3>Gynecomastia Treatment</h3>
                        <p>When the patient consults with their doctor regarding the symptoms, the doctor will conduct a detailed medical and physical examination for the patient. This will include a detailed medical history about the drugs he is taking, diseases he might be suffering from, etc. the doctor will also do a physical examination of the patient’s chest.</p>
                        <p>After this, some blood tests and imaging tests will be done for the patient to reach a definite diagnosis. Blood tests are done to check the levels of hormones in the body and X-Ray (mammogram), etc are done to rule out any other abnormality in the breast.</p>
                        <p>Once the diagnosis of gynecomastia is made, there are many gynecomastia treatment options that are available for the patient. </p>
                        <p>While most cases of gynecomastia resolve on their own, if it is being caused by some underlying disease, then the disease has to be treated first. Gynecomastia treatment for enlarged breast tissue due to any medication can be treated by discontinuing or adjusting the dose of the medication. </p>
                        <p>For other cases, the gynecomastia treatment options include:</p>
