                        <h2>Gynecomastia Symptoms </h2>
                        <p>Because of the development of extra breast tissue or deposition of excess fat in the breast, the patients can observe the following <b>gynecomastia symptoms</b>:</p>
                        <ul class="disc_list">
                            <li>Increase in the size of the breasts</li>
                            <li>Swollen breast tissue</li>
                            <li>Breast tenderness</li>
                        </ul>
                        <p>While all these symptoms can be a cause for concern for the patient and should be reported to the doctor, there are some <b>gynecomastia symptoms</b> that, when seen, should be reported immediately to a professional. These include:</p>
                        <ul class="disc_list">
                            <li>The very fast increase in the size of the breast tissue</li>
                            <li>Discharge from the nipple</li>
