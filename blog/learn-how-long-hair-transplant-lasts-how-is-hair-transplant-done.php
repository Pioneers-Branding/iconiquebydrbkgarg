<h2 class="blog_heading">How is Hair Transplant Done?</h2>
<p>To provide the patients with a comprehensive view, Dr. BK Garag has listed the steps of hair transplant in detail. If you are wondering- How is Hair Transplant Done? Then read along further to understand the process.</p>
<h3><strong>Preparation for the surgical procedure</strong></h3>
<p>In the first step, the patients are prepared for their hair transplant surgery. They are provided with the necessary medications, and the required physical tests are performed.</p>
<h3><strong>Trimming of Donor Area</strong></h3>
<p>The area where the hair follicles would be transplanted (donor area) is prepared in the next step. The donor area is trimmed. This is usually done before the surgery starts.</p>
<h3><strong>Donor area prepared for the surgery.</strong></h3>
<p>After the donor area is trimmed, the patient is administered with local anesthesia. The patient is then prepared for the surgery. Furthermore, the tissue (hair follicles) in the donor area is removed surgically. The donor area is also sutured, and the procedure starts.</p>
<h3><strong>The sutured donor area is combed.</strong></h3>
<p>The sutures present in the donor area are hidden from the patient&rsquo;s hair and combed over them. Almost ten days after the hair transplant surgery, these sutures are removed.</p>
<h3><strong>The Donor tissue is trimmed into follicular unit grafts.</strong></h3>
<p>The surgical technicians then use microscopes to view the donor tissue for dissecting and preparing follicular units hair grafts.</p>
<h3><strong>The Bald recipient area is prepared.</strong></h3>
<p>After local anesthesia is administered to the patient, the balding recipient area is also prepared for the surgical process. No removal or trimming of hair is required at the top of the recipient area.</p>
<h3><strong>In the Balding area, incisions are made.</strong></h3>
<p>The incisions are made in an irregular pattern in the recipient area. After that, the follicular unit grafts are placed in tiny incisions. According to the densities, the grafts are placed. The smallest grafts are placed in the front of the hairline.</p>
<p>The tiny incisions made with the transplanted hair follicles would be visible on the patient&rsquo;s operated area for some time after the surgery. The marks of the incision would heal naturally. The redness in the recipient area vanishes naturally within a week.</p>

<h2 class="blog_heading">How long does Hair Transplant Last?</h2>
<p>Hair transplantation is also commonly referred to as hair restoration. It is a procedure that involves the technique of micrografting where the donated hair follicles are planted in the area that is experiencing hair thinning.</p>
<p>The people who are contemplating undergoing hair transplants often have the question- How long Hair Transplant Last? The studies conducted have shown that the results of hair transplants are visibly long-lasting.</p>
<p>The procedure of hair transplant is often considered to be permanent. The hair transplant process is time-consuming, but it has a recovery and healing time of its own. After the hair follicles are grafted into the area experiencing hair thinning, it takes six to twelve months to heal.</p>
<p>However, once the healing process is completed, the transplanted hair follicles grow and gradually cover the bald areas. With passing time, the hair continues to grow naturally. Generally, the movement of the hair follicles is permanent. Once the hair transplant procedure is completed, there is no way that the original position can be returned.</p>
<p>Like the rest of the hair follicles, the transplanted hair follicles have a lifespan of their own. At some point, the transplanted hair follicles may gradually stop growing as much hair as they used to do previously.</p>
<p>However, there is also a possibility that the first hair transplantation procedure will not be the last. Some patients may require multiple sessions after their first hair transplant surgery to achieve the desired results.&nbsp;</p>
<p>But in general, the procedure of hair is considered long-lasting and is referred to as a permanent solution. It takes time to recover and heal, but hair transplant surgery is the best solution for people facing baldness and hair thinning.</p>
