                        <h3 class="blog_heading">Procedure for microneedling</h3>
                        <p>In the clinic, first, your skin specialist will cleanse your skin/target area and a numbing cream is applied. This will lessen the discomfort and you will not feel any pain. Next, your skin expert will use a professional micro-needling device to create microchannels on your skin. Total treatment will take around 30 to 40 min and there is no downtime.</p>
