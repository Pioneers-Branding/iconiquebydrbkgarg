                        <h3 class="blog_heading">Are there any risks or side effects?</h3>
                        <p>
                            <b>Derma roller side effects for Skin:</b><br>
                            Post-treatment, you may experience slight redness on the skin and the skin may feel dry for the next few days. Your skin will also be sensitive to the Sun and it is better to avoid direct sun exposure for a few days. Other derma roller side effects on the skin include temporary skin irritation or infection in some cases. You can use ice packs to soothe your skin.
                        </p>
                        <p>Bleeding after micro-needling is very rare. You can discuss the risk factors with your skin specialist and ways to minimize these.</p>

