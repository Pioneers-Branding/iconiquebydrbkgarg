<h2><strong>Procedure of hair transplant</strong></h2>
<ol>
<li aria-level="1">Hair follicles are removed from the back and relocated to the hairless patches.</li>
<li aria-level="1">The donor area is trimmed and prepared for the procedure.</li>
<li aria-level="1">Local anaesthesia is given after trimming.</li>
<li aria-level="1">The sutures in the donor area are combed over them.</li>
<li aria-level="1">Using a microscope, the donor tissue is prepared for the hair transplant.</li>
<li aria-level="1">The recipient area is prepared for the hair transplant.</li>
<li aria-level="1">The isolated hair grafts are placed according to the hair density and hairline.</li>
<li aria-level="1">Care instructions are given to the patient to follow and adhere to.</li>
</ol>

<h2><strong>How to prepare for the surgery?</strong></h2>
<ul>
<li aria-level="1">If you are a smoker, you need to stop at least 2 weeks before the procedure.</li>
<li aria-level="1">Inform the surgeon in case you are taking any medications. He/she may ask you to withdraw them for a while.</li>
<li aria-level="1">Avoid spicy food before the surgery.</li>
<li aria-level="1">Let your doctor know if you have any allergies.</li>
<li aria-level="1">Wash your hair 2 days prior to the procedure using a shampoo.</li>
</ul>

<h2><strong>Pre and post-operative care</strong></h2>
<ul>
<li aria-level="1">Stop any medications that you may be taking or any supplements as per advice.</li>
<li aria-level="1">Avoid consuming steroid preparations or any topical applications that may increase the risk of bleeding. </li>
<li aria-level="1">Stay away from alcohol and smoking.</li>
<li aria-level="1">Sleep well before the procedure.</li>
<li aria-level="1">Avoid the use of hair gel, spray or any other hair cosmetics.</li>
<li aria-level="1">Stay away from strenuous exercise for a week before the hair transplant.</li>
<li aria-level="1">Avoid the use of wigs. </li>
<li aria-level="1">Have light food and avoid coffee and other stimulants.</li>
<li aria-level="1">Sleep with your head at a higher level for about 7 days.</li>
<li aria-level="1">Wash your hair gently.</li>
<li aria-level="1">Do not scratch your scalp.</li>
<li aria-level="1">Avoid getting exposed to the sun excessively.</li>
<li aria-level="1">Continue taking oral medications as prescribed after the hair transplant.</li>
</ul>

<h2><strong>Dos and dont’s after the surgery</strong></h2>
<ul>
<li aria-level="1">Follow the post-operative care routine as prescribed.</li>
<li aria-level="1">Take antibiotics and use pain medication only if necessary.</li>
<li aria-level="1">Watch for any signs of infection and report to the doctor immediately.</li>
<li aria-level="1">It is better to avoid smoking or taking blood thinners until it heals and settles in. </li>
<li aria-level="1">Avoid activities that may increase sweating on the scalp.</li>
<li aria-level="1">Use an ammonia-free shampoo or a recommended hair care product.</li>
<li aria-level="1">Avoid weight lifting or excessive gymming.</li>
</ul>

