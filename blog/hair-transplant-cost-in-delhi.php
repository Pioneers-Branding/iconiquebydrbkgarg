<h2><strong>Who can opt for a hair transplant?</strong></h2>
<p>If you belong to one or more of the following categories, then you may be the right candidate for a hair transplant.</p>
<ul>
<li>1. You are experiencing thinning of hair</li>
<li>2. Your bald patches are concerning you</li>
<li>3. You are well into your 20s, 30s or 40s.</li>
<li>4. There is sufficient hair on your scalp for implantation</li>
<li>5. You have enough hair follicles that can potentially function and give good results after the hair transplant</li>
<li>6. You have male pattern baldness </li>
<li>7. Your hair loss has been progressive for the past 3–5 years</li>
<li>8. You have lost hair due to trauma or burns</li>
<li>9. When you have realistic expectations about your hair restoration</li>
</ul>

<br>
<h2><strong>Who should not opt for a hair transplant</strong></h2>
<ul>
<li>1. If you have no hair since birth</li>
<li>2. If you are under 20 years of age</li>
<li>3. Those with kidney disease, severe bleeding complications, diabetes, etc</li>
<li>4. When you have had a reaction to anesthesia in the past</li>
<li>5. Your existing medical condition does not let you have anesthesia as part of a procedure</li>
<li>6. When you have a type of hair loss known as scarring alopecia </li>
<li>7. If you have been diagnosed with a type of hair loss known as telogen effluvium</li>
<li>8. Any symptoms that have an impending diagnosis</li>
<li>9. If you are an active smoker, you may need to stop smoking before the transplant.</li>
<li>10. When your scalp has a flare-up of psoriasis</li>
<li>11. If the grafts have popped up or caused excessive bleeding on a current or previous session</li>
<li>12. If you have blood clotting disorders, such as haemophilia, you need to consult with your doctor to see if you are fit to have the procedure.</li>
</ul>
