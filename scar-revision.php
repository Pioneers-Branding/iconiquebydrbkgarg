            <b>• Scar Modulation Therapy</b><br>
            Topical silicone gel is used on the scars. This gel is invisible, self-drying, spreadable and on regular administration of this gel, the scars show noticeable rectification. This gel dries up in 4-5 minutes and works for 24 hours. This helps in the improvement of pigmentation, the texture of the scarred skin. <br>
